#!/usr/bin/env node
/**
 * Regenerate docs/folklore.md from apps/web/src/lib/folklore.ts so the
 * contributor-facing doc and the public /folklore page can never disagree.
 * Same pattern as scripts/gen-okf.ts. Run: bun run gen:folklore
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const { FOLKLORE } = await import(
  pathToFileURL(new URL("../apps/web/src/lib/folklore.ts", import.meta.url).pathname).href
);

const rows = FOLKLORE.map(
  (f, i) =>
    `| ${i + 1} | "${f.claim}" | **${f.verdict}.** ${f.reality}${
      f.insteadRules?.length ? ` We check instead: ${f.insteadRules.map((r) => `\`${r}\``).join(", ")}.` : ""
    } | [${f.sourceTitle}](${f.sourceUrl}) |`,
).join("\n");

writeFileSync(
  new URL("../docs/folklore.md", import.meta.url),
  `<!-- GENERATED by scripts/gen-folklore-doc.mjs from apps/web/src/lib/folklore.ts. Edit that file, then run \`bun run gen:folklore\`. -->

# SEO folklore: checks pseolint refuses to run

**Status:** living document, regenerated from the same data as the public
[/folklore](https://pseolint.dev/folklore) page.

The blind-spots spec ([2026-05-03-pseolint-blind-spots.md](./superpowers/specs/2026-05-03-pseolint-blind-spots.md))
lists real signals we don't detect yet. This document is the opposite: checks
that are widely repeated in SEO folklore but contradicted by the primary
sources. pseolint deliberately does NOT flag any of these, and pull requests
adding them will be declined with a link here.

A linter earns trust by what it refuses to flag as much as by what it catches.

| # | Folklore claim | Verdict | Primary source |
|---|---------------|---------|----------------|
${rows}

## How to use this list

- **Proposing a rule?** If the claim's only support is an SEO blog, a tool
  vendor's checklist, or "everyone knows", find the primary source first. If
  the primary source contradicts it, the rule lands here instead of in the
  engine.
- **A rule here later becomes real?** Google's docs change (see #5: the 15 MB
  limit was true for years). Each entry cites a living doc; re-verify against
  it before arguing from this table.
- **Editing?** Change \`apps/web/src/lib/folklore.ts\` and run
  \`bun run gen:folklore\`. Editing this file directly will be overwritten.
`,
  "utf8",
);
console.log(`docs/folklore.md regenerated from ${FOLKLORE.length} entries`);
