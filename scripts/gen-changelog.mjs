import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const webDir = path.join(rootDir, "apps", "web");

const PACKAGES = [
  { dir: "packages/core", name: "@pseolint/core", channel: "npm · engine" },
  { dir: "packages/cli", name: "pseolint", channel: "npm · CLI" },
  { dir: "packages/mcp", name: "@pseolint/mcp", channel: "npm · MCP server" },
  { dir: "packages/action", name: "@pseolint/action", channel: "GitHub Action" },
  { dir: "apps/extension", name: "@pseolint/extension", channel: "Chrome Web Store" },
  { dir: "apps/web", name: "@pseolint/web", channel: "hosted app" },
];

function read(rel) {
  try {
    return fs.readFileSync(path.join(rootDir, rel), "utf-8");
  } catch {
    return null;
  }
}

function parseChangelog(md) {
  return md
    .split(/^## /m)
    .slice(1)
    .map((sec) => {
      const nl = sec.indexOf("\n");
      const version = (nl === -1 ? sec : sec.slice(0, nl)).trim();
      const body = nl === -1 ? "" : sec.slice(nl + 1);
      const changes = [];
      for (const raw of body.split("\n")) {
        const bullet = raw.match(/^\s*-\s+(.*)/);
        if (bullet) {
          const text = bullet[1].replace(/^[0-9a-f]{7,}:\s*/i, "");
          if (text.trim()) changes.push(text.trim());
        } else if (raw.trim() && /^\s+/.test(raw) && changes.length) {
          changes[changes.length - 1] += " " + raw.trim();
        }
      }
      return { version, changes };
    })
    .filter((e) => e.version);
}

const packages = PACKAGES.map((p) => {
  let version = "—";
  const pkgJson = read(path.join(p.dir, "package.json"));
  if (pkgJson) {
    try {
      version = JSON.parse(pkgJson).version ?? "—";
    } catch {}
  }
  const md = read(path.join(p.dir, "CHANGELOG.md"));
  return {
    name: p.name,
    channel: p.channel,
    version,
    entries: md ? parseChangelog(md) : [],
  };
});

const outPath = path.join(webDir, "src", "lib", "changelog-data.ts");
const content = `// GENERATED by scripts/gen-changelog.mjs. Do not edit directly.
// Run: bun run gen:changelog

export type ChangelogEntry = {
  version: string;
  changes: string[];
};

export type PackageChangelog = {
  name: string;
  channel: string;
  version: string;
  entries: ChangelogEntry[];
};

export const CHANGELOG_PACKAGES: PackageChangelog[] = ${JSON.stringify(packages, null, 2)};
`;

fs.writeFileSync(outPath, content, "utf-8");
console.log(`Generated changelog data at ${path.relative(rootDir, outPath)} (${packages.length} packages)`);
